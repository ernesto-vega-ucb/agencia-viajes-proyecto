REQUIRED_KEYS = (
    "id",
    "code",
    "title",
    "destination",
    "country",
    "description",
    "category",
    "durationDays",
    "basePrice",
    "currency",
    "rating",
    "startDates",
)


def main() -> None:
    if not (15 <= len(PACKAGES) <= 20):
        raise SystemExit("El conjunto sintético de paquetes debe tener entre 15 y 20 registros")
    for package in PACKAGES:
        missing = [key for key in REQUIRED_KEYS if key not in package]
        if missing:
            raise SystemExit(f"Registro {package['code']} sin claves: {missing}")
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        json.dumps(PACKAGES, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"{len(PACKAGES)} paquetes sintéticos escritos en {OUT_PATH}")


if __name__ == "__main__":
    main()
